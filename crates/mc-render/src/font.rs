/// 8x8 ASCII bitmap font generator (printable ASCII 32..=126 packed into a 128x64 RGBA texture).
/// Uses clean, readable 5x7 glyphs inside 8x8 cells so every HUD label, F3 debug line,
/// chat line, inventory count, and button caption renders crisply without external font files.

pub const FONT_COLS: u32 = 16;
pub const FONT_ROWS: u32 = 6;
pub const CELL_W: u32 = 8;
pub const CELL_H: u32 = 8;
pub const FONT_TEX_W: u32 = FONT_COLS * CELL_W;
pub const FONT_TEX_H: u32 = FONT_ROWS * CELL_H;

pub fn build_font_rgba() -> Vec<u8> {
    let mut rgba = vec![0u8; (FONT_TEX_W * FONT_TEX_H * 4) as usize];
    for ch in 32u8..=126u8 {
        let idx = (ch - 32) as u32;
        let cx = (idx % FONT_COLS) * CELL_W;
        let cy = (idx / FONT_COLS) * CELL_H;
        let rows = glyph_5x7(ch);
        for (ry, bits) in rows.iter().enumerate() {
            for rx in 0..5u32 {
                if (bits >> (4 - rx)) & 1 == 1 {
                    let px = cx + 1 + rx;
                    let py = cy + ry as u32;
                    let off = ((py * FONT_TEX_W + px) * 4) as usize;
                    rgba[off..off + 4].copy_from_slice(&[255, 255, 255, 255]);
                }
            }
        }
    }
    rgba
}

pub fn char_uv(ch: char) -> [f32; 4] {
    let code = if ch.is_ascii() && (ch as u32) >= 32 && (ch as u32) <= 126 {
        (ch as u32) - 32
    } else {
        ('?' as u32) - 32
    };
    let col = code % FONT_COLS;
    let row = code / FONT_COLS;
    let u0 = (col * CELL_W) as f32 / FONT_TEX_W as f32;
    let v0 = (row * CELL_H) as f32 / FONT_TEX_H as f32;
    let u1 = ((col + 1) * CELL_W) as f32 / FONT_TEX_W as f32;
    let v1 = ((row + 1) * CELL_H) as f32 / FONT_TEX_H as f32;
    [u0, v0, u1, v1]
}

